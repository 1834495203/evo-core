"""Public structural interfaces. Implementations need not inherit application classes."""
from typing import Protocol, Any


class DocumentModule(Protocol):
    def put(self, kind: str, text: str, *, record_id: str = "", **details) -> dict: ...
    def get(self, record_id: str) -> dict: ...
    def search(self, query: str = "", kind: str = "") -> list[dict]: ...
    def index(self, limit: int = 15) -> list[dict]: ...


class LiteratureModule(Protocol):
    def search(self, query: str, limit: int = 5) -> list[dict]: ...
    def add(self, title: str, abstract: str, notes: str, url: str, **metadata) -> dict: ...
    def library(self, query: str = "", tag: str = "", limit: int = 50) -> list[dict]: ...
    def read(self, paper_id: str, offset: int = 0, limit: int = 16000, focus_query: str = "") -> dict: ...
    def annotate(self, paper_id: str, notes: str, tags: list[str] | None = None) -> dict: ...


class CodingModule(Protocol):
    def task(self, text: str) -> dict: ...
    def implement(self, task_id: str, instruction: str = "", *, ctx: Any = None) -> dict: ...
    def submit(self, task_id: str, source_dir: str, files: list[str], run: dict) -> dict: ...
    def review(self, submission_id: str, approved: bool, notes: str) -> dict: ...
    def authorize(self, submission_id: str, spec: Any) -> dict[str, str]: ...
    def inspect(self, submission_id: str, file_path: str = "") -> dict: ...
    def test_submission(self, submission_id: str, *, timeout: int = 60, test_paths: list[str] | None = None, python_executable: str | None = None) -> dict: ...


class ContextModule(Protocol):
    def load(self, session: str, role: str) -> list[dict]: ...
    def save(self, session: str, role: str, messages: list[dict]) -> None: ...
    def offload_tool_output(self, session: str, role: str, tool_name: str, content: str, max_chars: int = 12000) -> str: ...
    def edit_and_compact(self, session: str, role: str, messages: list[dict], **kwargs) -> list[dict]: ...


class TraceModule(Protocol):
    def log_span(self, kind: str, payload: dict) -> None: ...
    def log_job(self, job: Any) -> None: ...
    def log_llm_call(self, actor: str, call_num: int, messages: list[dict], response: Any, **kwargs) -> None: ...
    def query(self, after: int = 0, limit: int = 100, actor: str = "", run_id: str = "") -> dict: ...


class ExperimentModule(Protocol):
    def submit(self, study_id, plan_version, spec, request_key, **kwargs): ...
    def get(self, job_id): ...
    def list_jobs(self, study_id: str) -> list[dict]: ...
    def verify(self, job_id: str, check_entrypoint: str, **kwargs): ...
    def invalidate(self, job_id: str, reason: str, **kwargs): ...
    def annotate(self, job_id: str, note: str, *, kind: str = "observation", registry: Any = None) -> dict: ...
    def worker(self, worker_id, **kwargs): ...
    def worker_pool(self, max_workers=2, **kwargs): ...
