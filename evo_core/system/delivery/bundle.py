"""Portable research delivery assembled exclusively from archived evidence."""
import csv
import io
import json
import zipfile
from pathlib import Path


def export_bundle(system, study_id: str, destination: Path) -> Path:
    snapshot = system.queries.snapshot(study_id)
    reports = [r for r in snapshot["records"] if r["kind"] == "report"]
    if not reports:
        raise ValueError("Archive a report before exporting a research bundle")
    report = system.artifacts.read(reports[-1]["details"]["text_hash"])
    destination.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    with zipfile.ZipFile(destination, "w", zipfile.ZIP_DEFLATED) as out:
        out.writestr("final_report.md", report)
        for name, key in reports[-1]["details"].get("assets", {}).items():
            out.writestr(name, system.artifacts.read(key))
        out.writestr("report.qmd", b"---\ntitle: Research report\nformat: html\nexecute:\n  enabled: false\n---\n\n" + report)
        out.writestr("research_history.json", json.dumps(snapshot, ensure_ascii=False, indent=2))
        for record in snapshot["records"]:
            key = record["details"].get("content_hash") or record["details"].get("text_hash")
            if key:
                suffix = "json" if record["details"].get("content_type") == "application/json" else "md"
                out.writestr(f"documents/{record['id']}.{suffix}", system.artifacts.read(key))
        for job in snapshot["jobs"]:
            prefix = f"experiments/{job['id']}/"
            out.writestr(prefix + "job.json", json.dumps(job, ensure_ascii=False, indent=2))
            for name, key in job["manifest"].items():
                out.writestr(prefix + "source/" + name, system.artifacts.read(key))
            for name, key in (job.get("result") or {}).get("artifacts", {}).items():
                out.writestr(prefix + "artifacts/" + name, system.artifacts.read(key))
            for index, check in enumerate(job.get("checks", [])):
                for name, key in check.get("source_manifest", {}).items():
                    out.writestr(prefix + f"checks/{index}/source/" + name, system.artifacts.read(key))
                for name, key in check.get("artifacts", {}).items():
                    out.writestr(prefix + f"checks/{index}/artifacts/" + name, system.artifacts.read(key))
            metrics = (job.get("result") or {}).get("metrics", {})
            for key, value in metrics.items():
                rows.append([job["id"], job["status"], job.get("validity"), job["spec"]["protocol"],
                             job["spec"]["seed"], key, json.dumps(value, ensure_ascii=False)])
        table = io.StringIO(newline="")
        writer = csv.writer(table)
        writer.writerow(["job_id", "status", "validity", "protocol", "seed", "metric", "value"])
        writer.writerows(rows)
        out.writestr("metrics.csv", table.getvalue())
        out.writestr("README.md", """# Reproduction bundle
Read final_report.md and research_history.json for evidence, scope and limitations.
metrics.csv includes failed/invalid/unverified records; filter by status/validity before comparison.
Each experiments/<id>/job.json contains the original args, seed, protocol, data_version and source hashes.
To reproduce a run, use an environment matching its archived execution.json, cd to its source/
directory and run the recorded entrypoint with its recorded arguments (or python -m for module=true).
Set EVO_EXPERIMENT_SEED to the recorded seed. Output files are freshly generated by that run.
Checks are included in the source snapshot when declared; later check attempts are described in job.json.
The bundle does not install dependencies or guarantee that external datasets remain available.
Optional presentation: install Quarto and run `quarto render report.qmd`.
""")
    return destination
